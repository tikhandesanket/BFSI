function FallbackPanel({ fallbacks }) {
  const f = fallbacks || {};
  const recent = f.recent ?? [];
  const byReason = f.by_reason ?? {};
  const hasFallbacks = (f.total ?? 0) > 0;
  // Auto-roll the list as soon as there are a few entries so all fallback
  // questions cycle through the box. Content is duplicated so the -50% CSS
  // translate loops seamlessly; speed scales with the item count.
  const rolling = recent.length > 3;
  const rollItems = rolling ? [...recent, ...recent] : recent;
  const rollDuration = Math.max(12, recent.length * 3);
  return (
    <div
      className={
        "relative flex flex-col overflow-hidden rounded-2xl border p-5 lg:h-[300px] " +
        (hasFallbacks
          ? `border-rose-500/30 bg-rose-500/[0.07] ${HOVER.rose}`
          : `border-emerald-500/25 bg-emerald-500/[0.05] ${HOVER.emerald}`)
      }
    >
      {/* red glow accent */}
      {hasFallbacks && (
        <div className="pointer-events-none absolute -right-16 -top-16 h-40 w-40 rounded-full bg-rose-500/20 blur-3xl" />
      )}
      <div className="relative flex items-start justify-between gap-3">
        <div>
          <div className="flex items-center gap-2">
            <span
              className={
                "inline-flex h-7 w-7 items-center justify-center rounded-lg " +
                (hasFallbacks ? "bg-rose-500/20 text-rose-300" : "bg-emerald-500/15 text-emerald-300")
              }
            >
              <Icon name="alert" className="h-4 w-4" />
            </span>
            <h3 className="font-display text-base font-semibold text-white">
              Questions that triggered a fallback
            </h3>
          </div>
          <div className={"mt-1 text-[11px] " + (hasFallbacks ? "text-rose-200/80" : "text-emerald-200/80")}>
            No grounded, model-generated answer was produced
          </div>
        </div>
        <div className="text-right">
          <div className={"font-display text-3xl font-bold " + (hasFallbacks ? "text-rose-300" : "text-emerald-300")}>
            {f.total ?? 0}
          </div>
          <div className="text-[11px] text-ink-300">{pct(f.rate)} of queries</div>
        </div>
      </div>

      {/* Reason breakdown */}
      {Object.keys(byReason).length > 0 && (
        <div className="relative mt-4 flex flex-wrap gap-2">
          {Object.entries(byReason).map(([reason, count]) => {
            const meta = FALLBACK_META[reason] ?? { label: reason, color: "#f87171" };
            return (
              <span
                key={reason}
                className="inline-flex items-center gap-1.5 rounded-full border border-rose-400/30 bg-rose-500/10 px-2.5 py-1 text-[11px] text-rose-100"
              >
                <span className="h-2 w-2 rounded-sm" style={{ backgroundColor: meta.color }} />
                {meta.label}
                <span className="font-semibold text-white">{count}</span>
              </span>
            );
          })}
        </div>
      )}

      {/* Recent list — flex-fills so the card matches the Effort saved box height.
          Auto-rolls when it overflows; hover to pause. */}
      <div
        className={
          "fb-roll scrollbar-thin relative mt-4 min-h-0 flex-1 pr-1 " +
          (rolling ? "overflow-hidden" : "overflow-y-auto")
        }
      >
        {recent.length === 0 ? (
          <div className="flex h-24 items-center justify-center rounded-xl border border-emerald-500/20 bg-emerald-500/[0.05] px-4 text-center text-sm text-emerald-200/90">
            🎉 No fallbacks in this window — every question got a grounded answer.
          </div>
        ) : (
          <ul
            className={rolling ? "fb-roll-track" : ""}
            style={rolling ? { "--fb-roll-duration": `${rollDuration}s` } : undefined}
          >
            {rollItems.map((r, i) => {
              const meta = FALLBACK_META[r.reason] ?? { label: r.reason, color: "#f87171" };
              return (
                <li
                  key={i}
                  className="mb-1.5 flex items-start gap-3 rounded-xl border border-rose-400/20 bg-rose-500/[0.06] px-3 py-2 transition hover:border-rose-400/40 hover:bg-rose-500/[0.1]"
                >
                  <span
                    className="mt-1 inline-flex h-4 w-4 shrink-0 items-center justify-center rounded-full"
                    style={{ backgroundColor: meta.color + "33", color: meta.color }}
                  >
                    <Icon name="close" className="h-3 w-3" />
                  </span>
                  <div className="min-w-0 flex-1">
                    <div className="truncate text-sm text-ink-50" title={r.query}>
                      {r.query || "(empty query)"}
                    </div>
                    <div className="mt-0.5 flex items-center gap-1.5 text-[10px] uppercase tracking-wider">
                      <span style={{ color: meta.color }}>{meta.label}</span>
                      <span className="text-ink-500">·</span>
                      <span className="text-ink-400">{new Date(r.ts * 1000).toLocaleString()}</span>
                    </div>
                  </div>
                </li>
              );
            })}
          </ul>
        )}
      </div>
    </div>
  );
}

