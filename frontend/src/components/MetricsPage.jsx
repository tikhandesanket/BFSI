/* -------------------------------------------------------------- Stacked bars */
function BarChart({ title, subtitle, icon, days, series, formatValue, unit }) {
  // series: [{ key, label, color }]; each day has day[key] numbers.
  const max = Math.max(
    1,
    ...days.map((d) => series.reduce((s, ser) => s + (d[ser.key] || 0), 0)),
  );
  // Label every Nth day so a 30-day axis stays readable.
  const step = days.length > 20 ? 5 : days.length > 10 ? 3 : 1;
  const H = 150; // chart plot height (px)

  return (
    <div className={`surface p-5 ${HOVER.brand}`}>
      <div className="flex items-start justify-between gap-3">
        <div>
          <div className="flex items-center gap-2">
            <Icon name={icon} className="h-4 w-4 text-brand-300" />
            <h3 className="font-display text-base font-semibold text-white">{title}</h3>
          </div>
          <div className="mt-0.5 text-[11px] text-ink-300">{subtitle}</div>
        </div>
        <div className="flex flex-wrap items-center justify-end gap-x-3 gap-y-1">
          {series.map((s) => (
            <span key={s.key} className="inline-flex items-center gap-1.5 text-[11px] text-ink-200">
              <span className="h-2.5 w-2.5 rounded-[3px]" style={{ backgroundColor: s.color }} />
              {s.label}
            </span>
          ))}
        </div>
      </div>

      <div className="relative mt-5" style={{ height: H }}>
        {/* horizontal gridlines */}
        <div className="pointer-events-none absolute inset-0 flex flex-col justify-between">
          {[0, 1, 2, 3].map((i) => (
            <div key={i} className="border-t border-white/[0.05]" />
          ))}
        </div>
        {/* bars */}
        <div className="absolute inset-0 flex items-end gap-[3px]">
          {days.map((d, i) => {
            const total = series.reduce((s, ser) => s + (d[ser.key] || 0), 0);
            const tip = `${d.date}\n${series
              .map((s) => `${s.label}: ${formatValue ? formatValue(d[s.key] || 0) : d[s.key] || 0}`)
              .join("\n")}`;
            return (
              <div
                key={d.date}
                className="group relative flex h-full flex-1 flex-col justify-end"
                title={tip}
              >
                <div className="flex flex-col justify-end overflow-hidden rounded-t-md" style={{ height: "100%" }}>
                  {series.map((ser) => {
                    const v = d[ser.key] || 0;
                    const h = (v / max) * 100;
                    return (
                      <div
                        key={ser.key}
                        style={{
                          height: `${h}%`,
                          // glossy top highlight over the series colour
                          background: `linear-gradient(180deg, rgba(255,255,255,0.22) 0%, rgba(255,255,255,0) 45%), ${ser.color}`,
                          transition: "height 600ms cubic-bezier(0.22,1,0.36,1)",
                        }}
                        className="w-full opacity-85 group-hover:opacity-100"
                      />
                    );
                  })}
                </div>
                {/* x label */}
                {i % step === 0 && (
                  <span className="absolute -bottom-5 left-1/2 -translate-x-1/2 whitespace-nowrap text-[9px] text-ink-400">
                    {d.date.slice(5)}
                  </span>
                )}
                {/* hover total pill */}
                <span className="pointer-events-none absolute -top-6 left-1/2 z-10 hidden -translate-x-1/2 whitespace-nowrap rounded-md border border-white/10 bg-ink-950 px-1.5 py-0.5 text-[10px] font-medium text-white shadow-glow group-hover:block">
                  {formatValue ? formatValue(total) : total}
                  {unit ? ` ${unit}` : ""}
                </span>
              </div>
            );
          })}
        </div>
      </div>
      <div className="h-4" />
    </div>
  );
}

