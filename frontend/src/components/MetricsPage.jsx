/* ------------------------------------------------- Decision policy in force */
// The rules that decided each refusal/escalation are versioned, and every event
// is stamped with the version that produced it. Two things matter on screen:
// whether the numbers above span more than one rule set, and whether some of
// them predate versioning — both make the aggregates a blend rather than a rate.
function PolicyStrip({ policy, days }) {
  const p = policy || {};
  const mixed = (p.versions_in_window ?? 0) > 1;
  const unversioned = p.unversioned_events ?? 0;
  const escalationCounts = Object.entries(p.escalations_by_version || {});

  return (
    <div className={`surface mt-4 p-4 ${HOVER.sky}`}>
      <div className="flex flex-wrap items-center gap-x-3 gap-y-2">
        <span className="inline-flex h-7 w-7 items-center justify-center rounded-lg bg-sky-500/15 text-sky-300">
          <Icon name="shield" className="h-4 w-4" />
        </span>
        <h3 className="font-display text-base font-semibold text-white">Decision policy</h3>
        <code className="rounded-md bg-white/5 px-2 py-0.5 font-mono text-[11px] text-sky-200">
          {p.current || "—"}
        </code>
        <span className="text-[11px] text-ink-300">escalation rules</span>
        <code className="rounded-md bg-white/5 px-2 py-0.5 font-mono text-[11px] text-sky-200">
          {p.current_escalation || "—"}
        </code>
      </div>

      <div className="mt-2 text-[11px] text-ink-300">
        Every logged decision carries the version of the rules that produced it, so
        changing a threshold later cannot re-attribute past records.
      </div>

      {(mixed || unversioned > 0) && (
        <div className="mt-3 flex flex-col gap-2">
          {mixed && (
            <div className="rounded-lg border border-amber-400/30 bg-amber-400/10 px-3 py-2 text-[11px] text-amber-200">
              <span className="font-semibold">Rules changed inside this window.</span>{" "}
              {p.versions_in_window} policy versions cover the last {days} days — the
              rates above are a blend across them, not a single measurement.
            </div>
          )}
          {unversioned > 0 && (
            <div className="rounded-lg border border-white/10 bg-white/5 px-3 py-2 text-[11px] text-ink-300">
              <span className="font-semibold text-ink-200">{unversioned}</span> event
              {unversioned === 1 ? " was" : "s were"} recorded before policy versioning
              and cannot be attributed to a rule set. Left unlabelled rather than
              back-filled.
            </div>
          )}
        </div>
      )}

      {escalationCounts.length > 0 && (
        <div className="mt-3">
          <div className="text-[10px] uppercase tracking-wider text-ink-300">
            Escalations &amp; fallbacks by rule version
          </div>
          <div className="mt-1.5 flex flex-wrap gap-1.5">
            {escalationCounts
              .sort((a, b) => b[1] - a[1])
              .map(([version, count]) => (
                <span
                  key={version}
                  className="inline-flex items-center gap-1.5 rounded-md bg-white/5 px-2 py-1 font-mono text-[10px] text-ink-200"
                >
                  {version === "unversioned" ? (
                    <span className="text-ink-300">unversioned</span>
                  ) : (
                    <span className="text-sky-200">{version}</span>
                  )}
                  <span className="font-semibold text-white">{count}</span>
                </span>
              ))}
          </div>
        </div>
      )}
    </div>
  );
}

